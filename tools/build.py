"""Assemble README.md from the files listed in sections.txt.

One section per file in sections/. To reorder, move a line in sections.txt.
To hide a section, comment its line out with #. Then run:  python tools/build.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NOTICE = "<!-- Generated by tools/build.py from sections/. Edit those files, not this one. -->"


def main():
    order = [
        line.strip()
        for line in (ROOT / "sections.txt").read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]
    parts = []
    for name in order:
        path = ROOT / "sections" / name
        if not path.exists():
            raise SystemExit(f"sections.txt lists {name}, but sections/{name} does not exist")
        parts.append(path.read_text(encoding="utf-8").strip())
    (ROOT / "README.md").write_text(NOTICE + "\n\n" + "\n\n".join(parts) + "\n", encoding="utf-8")
    print(f"README.md built from {len(parts)} sections: {', '.join(order)}")


if __name__ == "__main__":
    main()
